CREATE TABLE IF NOT EXISTS users(
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(40) UNIQUE NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  cash DECIMAL(18,2) NOT NULL,
  deposited DECIMAL(18,2) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS holdings(
  user_id BIGINT NOT NULL, symbol VARCHAR(20) NOT NULL,
  qty DECIMAL(18,4) NOT NULL, avg_price DECIMAL(18,4) NOT NULL,
  PRIMARY KEY(user_id, symbol));
CREATE TABLE IF NOT EXISTS trades(
  id BIGINT AUTO_INCREMENT PRIMARY KEY, user_id BIGINT NOT NULL,
  symbol VARCHAR(20) NOT NULL, side VARCHAR(4) NOT NULL,
  qty DECIMAL(18,4) NOT NULL, price DECIMAL(18,4) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS chat(
  id BIGINT AUTO_INCREMENT PRIMARY KEY, username VARCHAR(40) NOT NULL,
  message VARCHAR(500) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
